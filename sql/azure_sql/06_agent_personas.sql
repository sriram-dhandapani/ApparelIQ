-- Step 9: map the SYNTHETIC personas (ref.person) to demo Entra users so the agent can add them to Teams chats and the
-- gateway can authorize approvals by UPN. Values come from config/deployment.local.json (agent_users_group.persona_map,
-- fallback_user) via scripts/setup_agent.py -> databricks/notebooks/03_apply_sql_script. Never hard-code tenant ids here.
-- Every persona without a dedicated demo user maps to the fallback user, which is also the escalation delegate
-- for markets without an accountable owner (DQ-12, BR/TRAIL).

SET XACT_ABORT ON;
BEGIN TRANSACTION;

DECLARE @map TABLE ([person_id] NVARCHAR(16) PRIMARY KEY, [upn] NVARCHAR(256), [oid] UNIQUEIDENTIFIER, [name] NVARCHAR(80));
-- One row per persona_map entry (generated by setup_databricks.py run-sql-agent; store managers like sm-us-1001 too).
INSERT INTO @map VALUES
{{PERSONA_MAP_ROWS}};

DELETE FROM [agent].[persona_user];

INSERT INTO [agent].[persona_user] ([person_id], [upn], [aad_object_id], [display_name], [is_escalation])
SELECT p.[person_id], COALESCE(m.[upn], N'{{UPN_FALLBACK}}'), COALESCE(m.[oid], '{{OID_FALLBACK}}'),
       COALESCE(m.[name], N'{{NAME_FALLBACK}}'), 0
FROM [ref].[person] p LEFT JOIN @map m ON m.[person_id] = p.[person_id];

INSERT INTO [agent].[persona_user] ([person_id], [upn], [aad_object_id], [display_name], [is_escalation])
VALUES (N'escalation', N'{{UPN_FALLBACK}}', '{{OID_FALLBACK}}', N'{{NAME_FALLBACK}}', 1);

-- Optional demo operator (agent_users_group.demo_operator): may take every decision on every case. Empty UPN = none.
INSERT INTO [agent].[persona_user] ([person_id], [upn], [aad_object_id], [display_name], [is_escalation])
SELECT N'operator', N'{{UPN_OPERATOR}}', TRY_CAST(N'{{OID_OPERATOR}}' AS UNIQUEIDENTIFIER), N'{{NAME_OPERATOR}}', 0
WHERE N'{{UPN_OPERATOR}}' <> N'' AND TRY_CAST(N'{{OID_OPERATOR}}' AS UNIQUEIDENTIFIER) IS NOT NULL;

COMMIT;
GO
SELECT [person_id], [upn], [display_name], [is_escalation] FROM [agent].[persona_user] ORDER BY [is_escalation] DESC, [person_id];
GO
